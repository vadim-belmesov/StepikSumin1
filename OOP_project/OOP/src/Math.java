public class Math {

    //Так как методы ниже не используют параметры объекта, 
    //можно их сделать static и привязать к классу
    static int multiple(int a, int b){
        return a * b;
    }

    static double multiple(double a, double b){
        return a * b;
    }

    static int multiple(int a){
        return a * a;
    }

    
}
